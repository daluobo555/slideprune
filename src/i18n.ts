/** Translate known module errors without discarding unknown diagnostic details. */
export function errorMessage(message: string, lang: Language): string {
  if (lang !== 'zh') return message;
  const translations: Record<string, string> = {
    'This file is empty. Choose a PDF document.': '文件为空，请选择有效的 PDF。',
    'Choose a PDF no larger than 40 MiB.': '请选择不超过 40 MiB 的 PDF。',
    'Choose a PDF with at most 250 pages.': '请选择不超过 250 页的 PDF。',
    'This file does not look like a PDF. Choose a valid PDF document.':
      '文件内容不是有效的 PDF，请重新选择。',
    'This PDF could not be read. It may be damaged or use an unsupported format.':
      '无法读取此 PDF，文件可能已损坏或使用了暂不支持的格式。',
    'Password-protected PDFs are not supported. Use an unencrypted copy you are allowed to edit.':
      '暂不支持加密 PDF，请使用你有权编辑的未加密副本。',
    'This PDF cannot be exported. It may be damaged or password-protected.':
      '无法导出此 PDF，文件可能已损坏或受密码保护。',
    'Select at least one page to export.': '请至少保留一页再导出。',
    'This browser cannot render PDF pages. Try a current desktop browser.':
      '当前浏览器无法渲染 PDF，请使用较新版本的桌面浏览器。',
    'Page images are too large for one document. Export fewer pages or turn off page images.':
      '原页图片超过单份文档的大小限制。请减少导出页数，或关闭原页图片。',
  };
  if (message.includes('optional content layers'))
    return '此 PDF 含有可选内容图层。为避免隐藏图层意外出现在导出文件中，本版暂不支持导出这类文件。';
  return translations[message] ?? message;
}
